import assert from "node:assert/strict";
import { allPages, parsePage, normalizeBills, voteKey } from "../lib/open-assembly/collector.ts";
const response = { service: [{ head: [{ list_total_count: 2 }, { RESULT: { CODE: "INFO-000" } }] }, { row: [{ id: "1" }, { id: "2" }] }] };
assert.equal(parsePage(response, "service").total, 2);
assert.deepEqual(parsePage({ RESULT: { CODE: "INFO-200" } }, "service"), { total: 0, rows: [] });
assert.throws(() => parsePage({ RESULT: { CODE: "ERROR-300" } }, "service"));
assert.throws(() => parsePage({ service: [{ row: [] }] }, "service"));
const key = row => String(row.id || "");
assert.deepEqual(await allPages(async page => ({ total: 2, rows: [{ id: String(page) }] }), key, 1), [{ id: "1" }, { id: "2" }]);
await assert.rejects(allPages(async () => ({ total: 2, rows: [{ id: "1" }] }), key, 1), /duplicate/);
await assert.rejects(allPages(async () => ({ total: 2, rows: [] }), key, 1), /incomplete/);
await assert.rejects(allPages(async page => ({ total: page === 1 ? 2 : 3, rows: [{ id: String(page) }] }), key, 1), /changed/);
const bills = normalizeBills([{ BILL_ID: "A", BILL_NAME: "가상법률안", PROPOSE_DT: "2026-01-01", RST_PROPOSER: "가상가", PUBL_PROPOSER: "가상가,가상나" }], [{ NAAS_NM: "가상가", NAAS_CD: "1" }, { NAAS_NM: "가상나", NAAS_CD: "2" }, { NAAS_NM: "가상나", NAAS_CD: "3" }]);
assert.equal(bills[0].authors.length, 2);
assert.equal(bills[0].authors[0].role, "대표발의");
assert.equal(bills[0].authors[1].memberId, null);
assert.equal(voteKey({ HG_NM: "가상가" }), "");
assert.equal(voteKey({ MONA_CD: "1", VOTE_DATE: "2026-01-01" }), "1|2026-01-01");
console.log("Collector offline checks passed");
